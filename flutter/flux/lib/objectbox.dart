import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';
import 'package:flux/entities/task.dart';
import 'package:flux/entities/project.dart';
import 'package:flux/entities/activity.dart';
import 'objectbox.g.dart'; // This will be generated by ObjectBox

/// Provides access to the ObjectBox Store throughout the app.
class ObjectBox {
  /// The Store of this app.
  static late Store store;

  // ObjectBox._create(this.store) {}

  /// Create an instance of ObjectBox to use throughout the app.
  // static Future<ObjectBox> create() async {
  static Future<void> create() async {
    final docsDir = await getApplicationDocumentsDirectory();
    // Future<Store> openStore() {...} is defined in the generated objectbox.g.dart
    store = await openStore(
      directory: p.join(docsDir.path, "obx"),
      macosApplicationGroup: "group.do.tempo.flux",
    );
    // return ObjectBox._create(store);
  }

  /// A Box for Task entities.
  static Box<TaskEntity> taskBox() => Box<TaskEntity>(store);

  /// A Box for TaskList entities.
  static Box<ProjectEntity> taskListBox() => Box<ProjectEntity>(store);

  /// A Box for Activity entities.
  static Box<ActivityEntity> activityBox() => Box<ActivityEntity>(store);
}
