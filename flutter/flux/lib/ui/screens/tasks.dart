import 'package:flutter/material.dart';
import 'package:flux/models/task.dart';
import 'package:flux/ui/widgets/task.dart';
import '../../objectbox.dart';
import '../../utils/date_formatter.dart';
import '../../objectbox.g.dart'; // This will be generated by ObjectBox
import 'task_editor.dart';

class TasksScreen extends StatefulWidget {
  @override
  _TasksScreenState createState() => _TasksScreenState();
}

class _TasksScreenState extends State<TasksScreen> {
  List<Task> _tasks = [];
  bool _isLoading = true;

  @override
  void initState() {
    super.initState();
    _loadTasks();
  }

  void _loadTasks() async {
    setState(() {
      _isLoading = true;
    });

    // Query tasks ordered by due date, excluding deleted tasks
    final query =
        ObjectBox.taskBox()
            .query(Task_.deleted.notEquals(true))
            .order(Task_.dueDate)
            .build();

    final tasks = query.find();
    query.close();

    setState(() {
      _tasks = tasks;
      _isLoading = false;
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text('Tasks'),
        actions: [
          IconButton(
            icon: Icon(Icons.add),
            onPressed: () {
              // Navigate to add task page
              Navigator.push(
                context,
                MaterialPageRoute(builder: (context) => TaskEditorScreen()),
              ).then((_) => _loadTasks());
            },
          ),
        ],
      ),
      body:
          _isLoading
              ? Center(child: CircularProgressIndicator())
              : _tasks.isEmpty
              ? _buildEmptyState()
              : _buildTaskList(),
    );
  }

  Widget _buildEmptyState() {
    return Center(
      child: Column(
        mainAxisAlignment: MainAxisAlignment.center,
        children: [
          Icon(Icons.task_alt, size: 80, color: Colors.grey[400]),
          SizedBox(height: 16),
          Text(
            'No tasks yet',
            style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
          ),
          SizedBox(height: 8),
          Text(
            'Add your first task to get started',
            style: TextStyle(color: Colors.grey[600]),
          ),
          SizedBox(height: 24),
          ElevatedButton.icon(
            icon: Icon(Icons.add),
            label: Text('Add Task'),
            onPressed: () {
              Navigator.push(
                context,
                MaterialPageRoute(builder: (context) => TaskEditorScreen()),
              ).then((_) => _loadTasks());
            },
          ),
        ],
      ),
    );
  }

  Widget _buildTaskList() {
    // Group tasks by due date for better organization
    final groupedTasks = <DateTime, List<Task>>{};

    for (final task in _tasks) {
      final dueDate = DateTime(
        task.dueDate.year,
        task.dueDate.month,
        task.dueDate.day,
      );

      if (!groupedTasks.containsKey(dueDate)) {
        groupedTasks[dueDate] = [];
      }

      groupedTasks[dueDate]!.add(task);
    }

    final sortedDates = groupedTasks.keys.toList()..sort();

    return ListView.builder(
      itemCount: sortedDates.length,
      itemBuilder: (context, dateIndex) {
        final date = sortedDates[dateIndex];
        final tasksForDate = groupedTasks[date]!;

        return Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Padding(
              padding: const EdgeInsets.fromLTRB(16, 16, 16, 8),
              child: Text(
                DateFormatter.formatDueDate(date),
                style: TextStyle(
                  fontWeight: FontWeight.bold,
                  color: Colors.blueGrey.shade700,
                  fontSize: 16,
                ),
              ),
            ),
            ...tasksForDate.map(
              (task) => TaskWidget(
                task: task,
                onTap: () {
                  Navigator.push(
                    context,
                    MaterialPageRoute(
                      builder: (context) => TaskEditorScreen(task: task),
                    ),
                  ).then((_) => _loadTasks());
                },
              ),
            ),
            if (dateIndex < sortedDates.length - 1)
              Divider(height: 16, thickness: 1),
          ],
        );
      },
    );
  }
}
