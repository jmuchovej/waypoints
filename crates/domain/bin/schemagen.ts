/**
 * Generates `typescript/schema.g.ts` from the specta-generated `typescript/types.g.ts`.
 *
 * Extracts discriminator values from the `Content` tagged union and string
 * literals from `TextMarkKind`, then produces `as const` objects with
 * PascalCase keys for use in the editor and app layers.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pascalCase } from "scule";

const root = resolve(import.meta.dirname, "..");
const typesPath = resolve(root, "typescript/types.g.ts");
const outPath = resolve(root, "typescript/schema.g.ts");

const src = readFileSync(typesPath, "utf-8");

// ── Helpers ──────────────────────────────────────────────────────────────────

/** Extract string literal values from a TS union type block. */
function extractUnionLiterals(typeName: string, source: string): string[] {
  // Match: export type TypeName = <body>;
  const re = new RegExp(`export type ${typeName}\\s*=[\\s\\S]*?(?=\\nexport |\\n$)`);
  const match = source.match(re);
  if (!match) throw new Error(`Could not find type "${typeName}" in types.g.ts`);

  const literals: string[] = [];
  for (const [, value] of match[0].matchAll(/"\s*([^"]+)\s*"/g)) {
    literals.push(value);
  }
  return literals;
}

/** Extract `type: "..."` discriminators from a tagged union. */
function extractTaggedDiscriminators(typeName: string, tag: string, source: string): string[] {
  const re = new RegExp(`export type ${typeName}\\s*=[\\s\\S]*?(?=\\nexport |\\n$)`);
  const match = source.match(re);
  if (!match) throw new Error(`Could not find type "${typeName}" in types.g.ts`);

  const values: string[] = [];
  const fieldRe = new RegExp(`${tag}:\\s*"([^"]+)"`, "g");
  for (const [, value] of match[0].matchAll(fieldRe)) {
    values.push(value);
  }
  return values;
}

/**
 * Resolve the type name to read discriminators from. specta-serde's
 * `PhasesFormat` splits directional types into `X_Serialize`/`X_Deserialize`
 * (leaving `X` as a bare `X_Serialize | X_Deserialize` union alias with no
 * inline fields), so prefer the `_Serialize` phase when it exists. Falls back
 * to the base name for symmetric types (e.g. `TextMarkKind`) or unified export.
 */
function resolvePhasedName(typeName: string, source: string): string {
  const serialize = `${typeName}_Serialize`;
  return new RegExp(`export type ${serialize}\\s*=`).test(source) ? serialize : typeName;
}

/** Build a `const X = { ... } as const;` block. */
function buildConstObject(name: string, values: string[]): string {
  const entries = values.map((v) => `  ${pascalCase(v)}: "${v}",`).join("\n");
  return `export const ${name} = {\n${entries}\n} as const;`;
}

// ── Extract & generate ───────────────────────────────────────────────────────

const contentTypes = extractTaggedDiscriminators(resolvePhasedName("Content", src), "type", src);
const inlineKinds = extractUnionLiterals(resolvePhasedName("TextMarkKind", src), src);

const output = [
  "// This file has been generated by schemagen. DO NOT EDIT.",
  "",
  `/** Content block type discriminators — must match Content["type"] from types.g.ts */`,
  buildConstObject("ContentType", contentTypes),
  "",
  "/** Inline mark kind discriminators — must match TextMarkKind from types.g.ts */",
  buildConstObject("InlineKind", inlineKinds),
  "",
].join("\n");

writeFileSync(outPath, output);
console.log(
  `wrote ${outPath} — ${contentTypes.length} content types, ${inlineKinds.length} inline kinds`,
);
