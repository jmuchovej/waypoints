/**
 * Post-processes `typescript/types.g.ts` after specta codegen.
 *
 * specta-typescript inlines every referenced type, so the editor's types.g.ts
 * duplicates types already exported by `@waypoints/domain`. This script
 * replaces those duplicates with a single `import type` statement so the
 * frontend shares one set of type identities.
 *
 * IMPORTANT: Run treefmt on both domain and editor `.g.ts` files *before*
 * this script so the output is in a predictable, semicolon-terminated format.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const domainRoot = resolve(root, "../domain");

// ── Helpers ──────────────────────────────────────────────────────────────────

function extractTypeNames(path: string): Set<string> {
  const src = readFileSync(path, "utf-8");
  const names = new Set<string>();
  for (const [, name] of src.matchAll(/^export type (\w+)/gm)) {
    names.add(name);
  }
  return names;
}

function genTypeImport(specifier: string, names: string[]): string {
  if (names.length === 0) return "";
  const sorted = [...names].sort();
  return `import type { ${sorted.join(", ")} } from "${specifier}";`;
}

function findJsdocStart(lines: string[], typeLine: number): number {
  if (typeLine === 0) return typeLine;
  let scan = typeLine - 1;
  while (scan >= 0 && lines[scan].trim() === "") scan--;
  if (scan >= 0 && lines[scan].trimEnd().endsWith("*/")) {
    while (scan >= 0 && !lines[scan].trimStart().startsWith("/**")) scan--;
    if (scan >= 0) return scan;
  }
  return typeLine;
}

function extractTypeDeclarations(source: string): Map<string, string> {
  const types = new Map<string, string>();
  const lines = source.split("\n");

  const declStarts: { name: string; line: number }[] = [];
  for (let i = 0; i < lines.length; i++) {
    const match = lines[i].match(/^export type (\w+)/);
    if (match) declStarts.push({ name: match[1], line: i });
  }

  for (let idx = 0; idx < declStarts.length; idx++) {
    const { name, line: typeLine } = declStarts[idx];
    const blockStart = findJsdocStart(lines, typeLine);

    let blockEnd: number;
    if (idx + 1 < declStarts.length) {
      blockEnd = findJsdocStart(lines, declStarts[idx + 1].line);
    } else {
      blockEnd = lines.length;
    }

    while (blockEnd > blockStart && lines[blockEnd - 1].trim() === "") blockEnd--;

    types.set(name, lines.slice(blockStart, blockEnd).join("\n"));
  }

  return types;
}

// ── Collect & categorize ─────────────────────────────────────────────────────

const domainTypes = extractTypeNames(resolve(domainRoot, "typescript/types.g.ts"));

const typesPath = resolve(root, "typescript/types.g.ts");
const file = readFileSync(typesPath, "utf-8");

// Strip the specta header comment
const body = file.replace(/^\/\/ This file has been generated by Specta\. DO NOT EDIT\.\n\n?/, "");

const allDecls = extractTypeDeclarations(body);

const fromDomain: string[] = [];
const localDefs: string[] = [];

for (const [name, decl] of allDecls) {
  if (domainTypes.has(name)) {
    fromDomain.push(name);
  } else {
    localDefs.push(decl);
  }
}

// ── Assemble ─────────────────────────────────────────────────────────────────

const imports = genTypeImport("@waypoints/domain", fromDomain);

const patched = [
  "// This file has been generated by Specta and post-processed by patch-types. DO NOT EDIT.",
  "",
  imports,
  "",
  localDefs.join("\n\n"),
  "",
].join("\n");

writeFileSync(typesPath, patched);

console.log(
  `patched editor types.g.ts — imported ${fromDomain.length} from domain, kept ${localDefs.length} local`,
);
