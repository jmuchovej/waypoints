//! What `release-plan` and `release-land bump-main` leave in a real working tree
//! for the pull-request step. The fixture has a real remote, because the planner
//! fetches the branch it writes to. Only a cut would reach the GitHub API, so
//! these run `advance` and the bump.

use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};
use tempfile::TempDir;

const GROUP_FILE: &str = r#"
[bookkeeping]
  paths        = [ "nix/releases/" ]
  ignore-revs  = ".git-blame-ignore-revs"
  bot-subjects = [ "chore(release):" ]

[group.waypoints]
  members  = [ "src-tauri", "crates/cartograph" ]
  anchor   = "src-tauri"
  tag      = "v{version}"
  breaking = "trailer:Covenant: break"
  floors   = [ "covenant-fixtures" ]
  fixtures = "covenant/fixtures/waypoints/"
  minted   = [ "cut", "advance", "promote", "patch" ]

[enforce]
  commits        = "conventional"
  summary-type   = "summary"
  version-writes = "botswain"
  fixtures       = "append-only"
  schema         = "current"
"#;

fn write(root: &Path, path: &str, text: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

fn git(root: &Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .args([
            "-c",
            "user.name=xtask",
            "-c",
            "user.email=xtask@waypoints.so",
            "-c",
            "commit.gpgsign=false",
        ])
        .args(args)
        .current_dir(root)
        .output()
        .expect("git runs");
    assert!(
        output.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap().trim().to_owned()
}

/// A manifest aligned the way tombi leaves ours, so a write that reformats shows.
fn manifest(name: &str, version: &str) -> String {
    format!("[package]\n  name    = \"{name}\"\n  version = \"{version}\"\n  edition = \"2024\"\n")
}

fn lock(version: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"Waypoints\"\nversion = \"{version}\"\n\n[[package]]\nname = \"cartograph\"\nversion = \"{version}\"\n"
    )
}

struct Fixture {
    _dir: TempDir,
    root: PathBuf,
}

impl Fixture {
    /// A checkout with `main` at `main_version` and `v0.2.x` at `series_version`,
    /// both also on the remote it was cloned from.
    fn new(main_version: &str, series_version: &str) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("checkout");
        let remote = dir.path().join("remote.git");
        fs::create_dir_all(&root).unwrap();

        write(
            &root,
            "Cargo.toml",
            "[workspace]\nresolver = \"3\"\nmembers = [ \"crates/cartograph\", \"src-tauri\" ]\n",
        );
        write(&root, "src-tauri/src/lib.rs", "");
        write(&root, "crates/cartograph/src/lib.rs", "");
        write(&root, "tooling/release-groups.toml", GROUP_FILE);
        write(&root, "covenant/fixtures/waypoints/README.md", "");
        write(&root, "nix/releases/stable.json", "");
        write(&root, ".git-blame-ignore-revs", "");
        write(&root, ".gitignore", "target/\n");

        git(&root, &["init", "-q", "-b", "main"]);
        let fixture = Self { _dir: dir, root };
        fixture.commit_versions(main_version, "feat: the tree");

        git(&fixture.root, &["checkout", "-q", "-b", "v0.2.x"]);
        fixture.commit_versions(series_version, "chore(release): cut");
        git(&fixture.root, &["checkout", "-q", "main"]);

        git(
            remote.parent().unwrap(),
            &["init", "-q", "--bare", "-b", "main", "remote.git"],
        );
        git(
            &fixture.root,
            &["remote", "add", "origin", remote.to_str().unwrap()],
        );
        git(&fixture.root, &["push", "-q", "origin", "main", "v0.2.x"]);
        fixture
    }

    fn commit_versions(&self, version: &str, subject: &str) {
        write(
            &self.root,
            "src-tauri/Cargo.toml",
            &manifest("Waypoints", version),
        );
        write(
            &self.root,
            "crates/cartograph/Cargo.toml",
            &manifest("cartograph", version),
        );
        write(&self.root, "Cargo.lock", &lock(version));
        git(&self.root, &["add", "-A"]);
        git(&self.root, &["commit", "-q", "-m", subject]);
    }

    fn xtask(&self, args: &[&str]) -> (Output, String) {
        let outputs = self.root.join("target/github-output");
        fs::create_dir_all(outputs.parent().unwrap()).unwrap();
        let output = Command::new(env!("CARGO_BIN_EXE_xtask"))
            .args(args)
            .current_dir(&self.root)
            .env("GITHUB_OUTPUT", &outputs)
            .output()
            .expect("xtask runs");
        let published = fs::read_to_string(&outputs).unwrap_or_default();
        (output, published)
    }

    /// Every tracked path changed in the working tree.
    fn changed(&self) -> Vec<String> {
        git(&self.root, &["diff", "--name-only"])
            .lines()
            .map(str::to_owned)
            .collect()
    }

    fn read(&self, path: &str) -> String {
        fs::read_to_string(self.root.join(path)).unwrap()
    }
}

fn assert_succeeded(output: &Output) {
    assert!(
        output.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

/// `--locked` fails on any disagreement between the manifests and the lockfile,
/// which is what proves the hand-edited entries are the ones cargo would write.
fn assert_cargo_agrees(root: &Path) {
    let output = Command::new("cargo")
        .args(["metadata", "--locked", "--offline", "--format-version", "1"])
        .current_dir(root)
        .output()
        .expect("cargo runs");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

#[test]
fn advance_writes_the_whole_group_on_its_series() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");

    let (output, published) = fixture.xtask(&["release-plan", "advance"]);

    // `advance` reads the version from the tree it runs in, so a dispatch runs
    // it from the series.
    assert!(!output.status.success(), "main is not a preview");
    assert!(published.is_empty(), "{published}");

    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);
    let (output, published) = fixture.xtask(&["release-plan", "advance"]);
    assert_succeeded(&output);

    assert_eq!(git(&fixture.root, &["branch", "--show-current"]), "v0.2.x");
    assert_eq!(
        fixture.changed(),
        [
            "Cargo.lock",
            "crates/cartograph/Cargo.toml",
            "src-tauri/Cargo.toml"
        ]
    );
    assert_eq!(
        fixture.read("src-tauri/Cargo.toml"),
        manifest("Waypoints", "0.2.0-pre.2")
    );
    assert_eq!(
        fixture.read("crates/cartograph/Cargo.toml"),
        manifest("cartograph", "0.2.0-pre.2")
    );
    assert_eq!(fixture.read("Cargo.lock"), lock("0.2.0-pre.2"));
    assert_cargo_agrees(&fixture.root);

    for line in [
        "tag=v0.2.0-pre.2",
        "head=botswain/release-plan/v0.2.x",
        "title=chore(release): v0.2.x preview 0.2.0-pre.2",
        "paths=src-tauri/Cargo.toml,crates/cartograph/Cargo.toml,Cargo.lock",
    ] {
        assert!(
            published.lines().any(|out| out == line),
            "{line}: {published}"
        );
    }
}

/// The series moved after this job checked out, as a merged cherry-pick does.
#[test]
fn the_write_lands_on_the_series_as_the_remote_has_it() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");
    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);

    let other = fixture.root.parent().unwrap().join("other");
    git(
        fixture.root.parent().unwrap(),
        &["clone", "-q", "-b", "v0.2.x", "remote.git", "other"],
    );
    write(&other, "landed-meanwhile.txt", "");
    git(&other, &["add", "-A"]);
    git(&other, &["commit", "-q", "-m", "fix: landed meanwhile"]);
    git(&other, &["push", "-q", "origin", "v0.2.x"]);

    let (output, _) = fixture.xtask(&["release-plan", "advance"]);
    assert_succeeded(&output);
    assert!(fixture.root.join("landed-meanwhile.txt").exists());
}

#[test]
fn a_dry_run_names_the_pull_request_and_leaves_the_tree_clean() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");
    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);

    let (output, published) = fixture.xtask(&["release-plan", "advance", "--dry-run"]);
    assert_succeeded(&output);

    let stdout = String::from_utf8_lossy(&output.stdout);
    for named in [
        "chore(release): v0.2.x preview 0.2.0-pre.2",
        "botswain/release-plan/v0.2.x",
        "src-tauri/Cargo.toml,crates/cartograph/Cargo.toml,Cargo.lock",
    ] {
        assert!(stdout.contains(named), "{named}: {stdout}");
    }
    assert_eq!(fixture.changed(), Vec::<String>::new());
    // Without a landing the pull-request step has nothing to open.
    assert!(!published.contains("head="), "{published}");
}

/// A cut's second write, from the series the first left checked out.
#[test]
fn the_bump_moves_to_main_and_writes_the_whole_group_there() {
    let fixture = Fixture::new("0.2.0-nightly", "0.2.0-pre.1");
    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);

    let (output, published) =
        fixture.xtask(&["release-land", "bump-main", "--version", "0.3.0-nightly"]);
    assert_succeeded(&output);

    assert_eq!(git(&fixture.root, &["branch", "--show-current"]), "main");
    assert_eq!(
        fixture.read("src-tauri/Cargo.toml"),
        manifest("Waypoints", "0.3.0-nightly")
    );
    assert_eq!(
        fixture.read("crates/cartograph/Cargo.toml"),
        manifest("cartograph", "0.3.0-nightly")
    );
    assert_eq!(fixture.read("Cargo.lock"), lock("0.3.0-nightly"));
    assert_cargo_agrees(&fixture.root);

    for line in [
        "head=botswain/release-plan/main",
        "title=chore(release): main now targets 0.3.0-nightly",
        "paths=src-tauri/Cargo.toml,crates/cartograph/Cargo.toml,Cargo.lock",
    ] {
        assert!(
            published.lines().any(|out| out == line),
            "{line}: {published}"
        );
    }
}
