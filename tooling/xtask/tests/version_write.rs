//! What `release plan` leaves in a real working tree for the pull-request
//! step, and what `release groups project` writes from the group file. The
//! fixture has a real remote, because the planner fetches the branch it
//! writes to and reads the tags the remote holds. Nothing here reaches the
//! GitHub API: `advance` writes on its series, and a cut's first write lands
//! on `main` before any ref is minted.

use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};
use tempfile::TempDir;
use xtask::constants::GROUP_FILE;

/// The group file declaring the app at `app` and the library at `domain`,
/// aligned the way tombi leaves ours.
fn group_file(app: &str, domain: &str) -> String {
    format!(
        r#"[bookkeeping]
  paths        = [ "nix/releases/" ]
  bot-subjects = [ "chore(release):" ]

[group.domain]
  version  = "{domain}"
  members  = [ "crates/domain" ]
  tag      = "domain-v{{version}}"
  fixtures = "covenant/fixtures/domain/"

[group.waypoints]
  version  = "{app}"
  members  = [ "src-tauri", "crates/cartograph" ]
  tag      = "v{{version}}"
  fixtures = "covenant/fixtures/waypoints/"
"#
    )
}

/// The library's version in every fixture: a cut moves it from here.
const DOMAIN: &str = "0.1.0";

fn write(root: &Path, path: &str, text: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

fn git(root: &Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .args([
            "-c",
            "user.name=xtask",
            "-c",
            "user.email=xtask@waypoints.so",
            "-c",
            "commit.gpgsign=false",
        ])
        .args(args)
        .current_dir(root)
        .output()
        .expect("git runs");
    assert!(
        output.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap().trim().to_owned()
}

/// A manifest aligned the way tombi leaves ours, so a write that reformats shows.
fn manifest(name: &str, version: &str) -> String {
    format!("[package]\n  name    = \"{name}\"\n  version = \"{version}\"\n  edition = \"2024\"\n")
}

fn lock(app: &str, domain: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"Waypoints\"\nversion = \"{app}\"\n\n[[package]]\nname = \"cartograph\"\nversion = \"{app}\"\n\n[[package]]\nname = \"domain\"\nversion = \"{domain}\"\n"
    )
}

struct Fixture {
    _dir: TempDir,
    root: PathBuf,
}

impl Fixture {
    /// A checkout with `main` at `main_version` and `v0.2.x` at `series_version`,
    /// both also on the remote it was cloned from, and a library at [`DOMAIN`].
    fn new(main_version: &str, series_version: &str) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("checkout");
        let remote = dir.path().join("remote.git");
        fs::create_dir_all(&root).unwrap();

        write(
            &root,
            "Cargo.toml",
            "[workspace]\nresolver = \"3\"\nmembers = [ \"crates/cartograph\", \"crates/domain\", \"src-tauri\" ]\n",
        );
        write(&root, "src-tauri/src/lib.rs", "");
        write(&root, "crates/cartograph/src/lib.rs", "");
        write(&root, "crates/domain/src/lib.rs", "");
        write(&root, "covenant/fixtures/waypoints/README.md", "");
        write(&root, "covenant/fixtures/domain/README.md", "");
        write(&root, "nix/releases/stable.json", "");
        write(&root, ".git-blame-ignore-revs", "");
        write(&root, ".gitignore", "target/\n");

        git(&root, &["init", "-q", "-b", "main"]);
        let fixture = Self { _dir: dir, root };
        fixture.commit_versions(main_version, "feat: the tree");

        git(&fixture.root, &["checkout", "-q", "-b", "v0.2.x"]);
        fixture.commit_versions(series_version, "chore(release): cut");
        git(&fixture.root, &["checkout", "-q", "main"]);

        git(
            remote.parent().unwrap(),
            &["init", "-q", "--bare", "-b", "main", "remote.git"],
        );
        git(
            &fixture.root,
            &["remote", "add", "origin", remote.to_str().unwrap()],
        );
        git(&fixture.root, &["push", "-q", "origin", "main", "v0.2.x"]);
        fixture
    }

    fn commit_versions(&self, version: &str, subject: &str) {
        write(&self.root, GROUP_FILE, &group_file(version, DOMAIN));
        write(
            &self.root,
            "src-tauri/Cargo.toml",
            &manifest("Waypoints", version),
        );
        write(
            &self.root,
            "crates/cartograph/Cargo.toml",
            &manifest("cartograph", version),
        );
        write(
            &self.root,
            "crates/domain/Cargo.toml",
            &manifest("domain", DOMAIN),
        );
        write(&self.root, "Cargo.lock", &lock(version, DOMAIN));
        git(&self.root, &["add", "-A"]);
        git(&self.root, &["commit", "-q", "-m", subject]);
    }

    fn xtask(&self, args: &[&str]) -> (Output, String) {
        let outputs = self.root.join("target/github-output");
        fs::create_dir_all(outputs.parent().unwrap()).unwrap();
        let output = Command::new(env!("CARGO_BIN_EXE_xtask"))
            .args(args)
            .current_dir(&self.root)
            .env("GITHUB_OUTPUT", &outputs)
            .output()
            .expect("xtask runs");
        let published = fs::read_to_string(&outputs).unwrap_or_default();
        (output, published)
    }

    /// Every tracked path changed in the working tree.
    fn changed(&self) -> Vec<String> {
        git(&self.root, &["diff", "--name-only"])
            .lines()
            .map(str::to_owned)
            .collect()
    }

    fn read(&self, path: &str) -> String {
        fs::read_to_string(self.root.join(path)).unwrap()
    }
}

fn assert_succeeded(output: &Output) {
    assert!(
        output.status.success(),
        "{}\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

/// `--locked` fails on any disagreement between the manifests and the lockfile,
/// which is what proves the hand-edited entries are the ones cargo would write.
fn assert_cargo_agrees(root: &Path) {
    let output = Command::new("cargo")
        .args(["metadata", "--locked", "--offline", "--format-version", "1"])
        .current_dir(root)
        .output()
        .expect("cargo runs");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn assert_published(published: &str, lines: &[&str]) {
    for line in lines {
        assert!(
            published.lines().any(|out| out == *line),
            "{line}: {published}"
        );
    }
}

/// Scenario _An advance writes the app alone_: the group file's app version
/// and the app's manifests move together, and the library's line stays.
#[test]
fn advance_writes_the_whole_group_on_its_series() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");

    let (output, published) = fixture.xtask(&["release", "plan", "advance"]);

    // `advance` reads the version from the tree it runs in, so a dispatch runs
    // it from the series.
    assert!(!output.status.success(), "main is not a preview");
    assert!(published.is_empty(), "{published}");

    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);
    let (output, published) = fixture.xtask(&["release", "plan", "advance"]);
    assert_succeeded(&output);

    assert_eq!(git(&fixture.root, &["branch", "--show-current"]), "v0.2.x");
    assert_eq!(
        fixture.changed(),
        [
            "Cargo.lock",
            "crates/cartograph/Cargo.toml",
            "src-tauri/Cargo.toml",
            GROUP_FILE,
        ]
    );
    assert_eq!(fixture.read(GROUP_FILE), group_file("0.2.0-pre.2", DOMAIN));
    assert_eq!(
        fixture.read("src-tauri/Cargo.toml"),
        manifest("Waypoints", "0.2.0-pre.2")
    );
    assert_eq!(
        fixture.read("crates/cartograph/Cargo.toml"),
        manifest("cartograph", "0.2.0-pre.2")
    );
    assert_eq!(fixture.read("Cargo.lock"), lock("0.2.0-pre.2", DOMAIN));
    assert_cargo_agrees(&fixture.root);

    assert_published(
        &published,
        &[
            "tag=v0.2.0-pre.2",
            "head=botswain/release-plan/v0.2.x",
            "title=chore(release): v0.2.x preview 0.2.0-pre.2",
            "paths=tooling/release-groups.toml,src-tauri/Cargo.toml,crates/cartograph/Cargo.toml,Cargo.lock",
        ],
    );
}

/// The series moved after this job checked out, as a merged cherry-pick does.
#[test]
fn the_write_lands_on_the_series_as_the_remote_has_it() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");
    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);

    let other = fixture.root.parent().unwrap().join("other");
    git(
        fixture.root.parent().unwrap(),
        &["clone", "-q", "-b", "v0.2.x", "remote.git", "other"],
    );
    write(&other, "landed-meanwhile.txt", "");
    git(&other, &["add", "-A"]);
    git(&other, &["commit", "-q", "-m", "fix: landed meanwhile"]);
    git(&other, &["push", "-q", "origin", "v0.2.x"]);

    let (output, _) = fixture.xtask(&["release", "plan", "advance"]);
    assert_succeeded(&output);
    assert!(fixture.root.join("landed-meanwhile.txt").exists());
}

/// A dry run names what it would write and renders it — the group file's
/// hunk beside the manifests' in `series.patch` — and leaves the tree as it
/// was.
#[test]
fn a_dry_run_names_the_pull_request_and_leaves_the_tree_clean() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");
    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);
    let into = fixture.root.join("target/dry-run");

    let (output, published) = fixture.xtask(&[
        "release",
        "plan",
        "advance",
        "--dry-run",
        "--into",
        into.to_str().unwrap(),
    ]);
    assert_succeeded(&output);

    let stdout = String::from_utf8_lossy(&output.stdout);
    for named in [
        "chore(release): v0.2.x preview 0.2.0-pre.2",
        "botswain/release-plan/v0.2.x",
        "tooling/release-groups.toml,src-tauri/Cargo.toml,crates/cartograph/Cargo.toml,Cargo.lock",
    ] {
        assert!(stdout.contains(named), "{named}: {stdout}");
    }
    let patch = fs::read_to_string(into.join("series.patch")).unwrap();
    for hunk in [
        "--- a/tooling/release-groups.toml\n",
        "-  version  = \"0.2.0-pre.1\"\n+  version  = \"0.2.0-pre.2\"\n",
        "--- a/src-tauri/Cargo.toml\n",
        "--- a/crates/cartograph/Cargo.toml\n",
        "--- a/Cargo.lock\n",
    ] {
        assert!(patch.contains(hunk), "{hunk}: {patch}");
    }
    assert!(!patch.contains("crates/domain"), "{patch}");
    assert_eq!(fixture.changed(), Vec::<String>::new());
    // Without a landing the pull-request step has nothing to open.
    assert!(!published.contains("head="), "{published}");
}

/// Scenario _A cut writes the file with the manifests_: a cut's first write
/// is the main-side projection on `main` — the library the history moved and
/// the app's bump, in the group file and every member manifest — under a
/// summary whose headers the planner wrote to a body file for the
/// pull-request step. The series is opened later, from that write's merge
/// commit, so nothing touches it here.
#[test]
fn a_cut_writes_the_main_side_manifests_on_main_as_a_summary() {
    let fixture = Fixture::new("0.1.0-nightly", "0.2.0-pre.1");
    // Wherever the job happened to be: the write goes to `main`.
    git(&fixture.root, &["checkout", "-q", "v0.2.x"]);

    let (output, published) = fixture.xtask(&["release", "plan", "cut"]);
    assert_succeeded(&output);

    assert_eq!(git(&fixture.root, &["branch", "--show-current"]), "main");
    assert_eq!(
        fixture.changed(),
        [
            "Cargo.lock",
            "crates/cartograph/Cargo.toml",
            "crates/domain/Cargo.toml",
            "src-tauri/Cargo.toml",
            GROUP_FILE,
        ]
    );
    assert_eq!(
        fixture.read(GROUP_FILE),
        group_file("0.2.0-nightly", "0.1.1")
    );
    assert_eq!(
        fixture.read("src-tauri/Cargo.toml"),
        manifest("Waypoints", "0.2.0-nightly")
    );
    assert_eq!(
        fixture.read("crates/cartograph/Cargo.toml"),
        manifest("cartograph", "0.2.0-nightly")
    );
    assert_eq!(
        fixture.read("crates/domain/Cargo.toml"),
        manifest("domain", "0.1.1")
    );
    assert_eq!(fixture.read("Cargo.lock"), lock("0.2.0-nightly", "0.1.1"));
    assert_cargo_agrees(&fixture.root);

    assert_published(
        &published,
        &[
            "tag=v0.1.0-pre.1",
            "branch=v0.1.x",
            "next_main_version=0.2.0-nightly",
            "group_tags=domain-v0.1.1",
            "head=botswain/release-plan/main",
            "title=summary: cut 0.1.0-pre.1",
            "paths=tooling/release-groups.toml,src-tauri/Cargo.toml,crates/cartograph/Cargo.toml,crates/domain/Cargo.toml,Cargo.lock",
        ],
    );
    let body_path = published
        .lines()
        .find_map(|line| line.strip_prefix("body_path="))
        .unwrap_or_else(|| panic!("no body_path in {published}"));
    let body = fs::read_to_string(body_path).unwrap();
    assert!(
        body.contains("chore(domain): 0.1.1\nchore(waypoints): main now targets 0.2.0-nightly"),
        "{body}"
    );
}

/// Scenario _A hand-edited file is projected_: the library's manifest and
/// lockfile entry take the version the file now declares, and nothing else
/// moves.
#[test]
fn project_writes_a_hand_edited_file_into_its_manifests() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");
    write(
        &fixture.root,
        GROUP_FILE,
        &group_file("0.3.0-nightly", "0.2.0"),
    );

    let (output, _) = fixture.xtask(&["release", "groups", "project"]);
    assert_succeeded(&output);

    assert_eq!(
        fixture.changed(),
        ["Cargo.lock", "crates/domain/Cargo.toml", GROUP_FILE]
    );
    assert_eq!(
        fixture.read("crates/domain/Cargo.toml"),
        manifest("domain", "0.2.0")
    );
    assert_eq!(fixture.read("Cargo.lock"), lock("0.3.0-nightly", "0.2.0"));
    assert_cargo_agrees(&fixture.root);
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(
        stdout.contains("wrote crates/domain/Cargo.toml"),
        "{stdout}"
    );
}

/// Scenario _A new member takes its group's version_: a crate added to a
/// group at some other version is written to the group's.
#[test]
fn project_gives_a_new_member_its_group_s_version() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");
    write(
        &fixture.root,
        "Cargo.toml",
        "[workspace]\nresolver = \"3\"\nmembers = [ \"crates/cartograph\", \"crates/domain\", \"crates/domain-core\", \"src-tauri\" ]\n",
    );
    write(&fixture.root, "crates/domain-core/src/lib.rs", "");
    write(
        &fixture.root,
        "crates/domain-core/Cargo.toml",
        &manifest("domain-core", "0.0.0"),
    );
    write(
        &fixture.root,
        "Cargo.lock",
        &format!(
            "{}\n[[package]]\nname = \"domain-core\"\nversion = \"0.0.0\"\n",
            lock("0.3.0-nightly", DOMAIN)
        ),
    );
    write(
        &fixture.root,
        GROUP_FILE,
        &group_file("0.3.0-nightly", DOMAIN).replace(
            r#"members  = [ "crates/domain" ]"#,
            r#"members  = [ "crates/domain", "crates/domain-core" ]"#,
        ),
    );
    git(&fixture.root, &["add", "-A"]);
    git(
        &fixture.root,
        &["commit", "-q", "-m", "feat(domain): a core crate"],
    );

    let (output, _) = fixture.xtask(&["release", "groups", "project"]);
    assert_succeeded(&output);

    assert_eq!(
        fixture.changed(),
        ["Cargo.lock", "crates/domain-core/Cargo.toml"]
    );
    assert_eq!(
        fixture.read("crates/domain-core/Cargo.toml"),
        manifest("domain-core", DOMAIN)
    );
    assert!(
        fixture
            .read("Cargo.lock")
            .contains("name = \"domain-core\"\nversion = \"0.1.0\"\n"),
        "{}",
        fixture.read("Cargo.lock")
    );
    assert_cargo_agrees(&fixture.root);
}

/// Scenario _An agreeing tree is untouched_.
#[test]
fn project_on_an_agreeing_tree_changes_nothing() {
    let fixture = Fixture::new("0.3.0-nightly", "0.2.0-pre.1");

    let (output, _) = fixture.xtask(&["release", "groups", "project"]);
    assert_succeeded(&output);

    assert_eq!(fixture.changed(), Vec::<String>::new());
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(stdout.contains("already declares"), "{stdout}");
}
