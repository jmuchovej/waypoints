//! `THIRD-PARTY-NOTICES.md`: the attribution every distribution carries.
//!
//! Three inputs: the third-party registry, which no lockfile can stand in for;
//! `cargo-about` for the Rust dependencies; and the installed frontend packages.
//! The result is committed and kept in lockstep by `check-generated`. The list may
//! name a package the bundler tree-shook, which costs nothing; it never omits one,
//! which is what notice preservation cares about.

use super::{Entry, Kind, Registry};
use anyhow::{Context as _, Result, bail};
use serde_json::Value;
use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

/// Where the notices are committed, relative to the workspace root.
pub const NOTICES: &str = "docs/licensing/THIRD-PARTY-NOTICES.md";

/// The frontend package whose dependencies ship, relative to the workspace root.
const FRONTEND: &str = "src";

/// The workspace's own frontend packages, which are walked and not listed.
const FIRST_PARTY_SCOPE: &str = "@waypoints/";

const PREAMBLE: &str = "\
# Third-party notices

Waypoints includes the third-party software listed here, under the licenses shown. \
This file is generated by `cargo xtask license notices`; do not edit it by hand.
";

/// Renders the whole file.
pub fn generate(root: &Path) -> Result<String> {
    let registry = Registry::load(root)?;
    let in_tree = render_registry(root, &registry)?;
    let rust = cargo_about(root)?;
    let frontend = render_frontend(&frontend_packages(&root.join(FRONTEND))?);
    Ok(format!(
        "{PREAMBLE}\n## In-tree third-party code\n\n{in_tree}## Rust dependencies\n\n{}\n\n## Frontend dependencies\n\n{}\n",
        rust.trim(),
        frontend.trim(),
    ))
}

/// A license text, fenced so nothing inside it renders as Markdown.
fn fenced(text: &str) -> String {
    format!("~~~~text\n{}\n~~~~\n", text.trim_end())
}

fn render_registry(root: &Path, registry: &Registry) -> Result<String> {
    let mut entries: Vec<&Entry> = registry.entry.iter().collect();
    entries.sort_by(|a, b| a.path.cmp(&b.path));

    let mut rendered = String::new();
    for entry in entries {
        let kind = match entry.kind {
            Kind::Crate => "A vendored crate",
            Kind::Files => "Copied files",
            Kind::Portion => "A portion of a first-party file",
        };
        rendered.push_str(&format!(
            "### {}\n\n{kind} at `{}`. Copyright {}. Licensed `{}`.\n\n",
            entry.project, entry.path, entry.holder, entry.license
        ));
        let full = root.join(&entry.path);
        let dir = if full.is_dir() {
            full.as_path()
        } else {
            full.parent().unwrap_or(root)
        };
        for text in &entry.texts {
            let path = dir.join(text);
            let text = fs::read_to_string(&path)
                .with_context(|| format!("Failed to read {}", path.display()))?;
            rendered.push_str(&fenced(&text));
            rendered.push('\n');
        }
    }
    Ok(rendered)
}

/// The Rust dependencies, as `.config/about.hbs` renders them. A crate whose
/// license text cannot be found fails here, until a clarification supplies it.
fn cargo_about(root: &Path) -> Result<String> {
    let output = Command::new("cargo")
        .args([
            "about",
            "generate",
            "--workspace",
            "--config",
            ".config/about.toml",
            ".config/about.hbs",
        ])
        .current_dir(root)
        .output()
        .context("Failed to run `cargo about` — is cargo-about on PATH?")?;
    if !output.status.success() {
        bail!(
            "`cargo about` failed with {}:\n{}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8(output.stdout).context("`cargo about` wrote invalid UTF-8")
}

/// One frontend package, as the notices name it.
#[derive(Debug, PartialEq, Eq, PartialOrd, Ord)]
struct FrontendPackage {
    name: String,
    version: String,
    license: String,
    text: Option<String>,
}

/// Every package reachable from the frontend's manifest, found the way Node
/// finds them rather than through pnpm's listings, whose paths do not exist under
/// its global virtual store.
///
/// `devDependencies` count at the root, because the bundler reads them: `@tiptap/*`
/// ships from there. Platform packages are neither listed nor walked: only this
/// machine's are installed, so keeping them would make the file differ between a
/// Mac and a CI runner. They are native builds of tools, and the package they
/// serve is listed.
fn frontend_packages(frontend: &Path) -> Result<BTreeSet<FrontendPackage>> {
    let manifest = read_manifest(frontend)?;
    let mut pending: Vec<PathBuf> = dependencies(&manifest, true)
        .iter()
        .filter_map(|dependency| resolve(frontend, dependency))
        .collect();

    let mut seen = BTreeSet::new();
    let mut packages = BTreeSet::new();
    while let Some(dir) = pending.pop() {
        let dir = dir
            .canonicalize()
            .with_context(|| format!("Failed to resolve {}", dir.display()))?;
        if !seen.insert(dir.clone()) {
            continue;
        }
        let manifest = read_manifest(&dir)?;
        if ["os", "cpu", "libc"]
            .iter()
            .any(|key| manifest.get(key).is_some())
        {
            continue;
        }
        pending.extend(
            dependencies(&manifest, false)
                .iter()
                .filter_map(|dependency| resolve(&dir, dependency)),
        );

        let name = string_field(&manifest, "name");
        if name.is_empty() || name.starts_with(FIRST_PARTY_SCOPE) {
            continue;
        }
        packages.insert(FrontendPackage {
            name,
            version: string_field(&manifest, "version"),
            license: declared_license(&manifest),
            text: license_text(&dir)?,
        });
    }
    Ok(packages)
}

fn read_manifest(dir: &Path) -> Result<Value> {
    let path = dir.join("package.json");
    let text =
        fs::read_to_string(&path).with_context(|| format!("Failed to read {}", path.display()))?;
    serde_json::from_str(&text).with_context(|| format!("Failed to parse {}", path.display()))
}

fn string_field(manifest: &Value, field: &str) -> String {
    manifest
        .get(field)
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_owned()
}

/// A manifest's dependency names. Peers count: pnpm links them beside the package,
/// and one that resolves is a package the code may load.
fn dependencies(manifest: &Value, include_dev: bool) -> Vec<String> {
    let mut sections = vec!["dependencies", "optionalDependencies", "peerDependencies"];
    if include_dev {
        sections.push("devDependencies");
    }
    sections
        .into_iter()
        .filter_map(|section| manifest.get(section).and_then(Value::as_object))
        .flat_map(|section| section.keys().cloned())
        .collect()
}

/// Node's resolution: the nearest `node_modules` holding `dependency`, walking up
/// from `dir`. An optional or unmet peer dependency resolves to nothing.
fn resolve(dir: &Path, dependency: &str) -> Option<PathBuf> {
    dir.ancestors().find_map(|ancestor| {
        let modules = if ancestor
            .file_name()
            .is_some_and(|name| name == "node_modules")
        {
            ancestor.to_path_buf()
        } else {
            ancestor.join("node_modules")
        };
        let candidate = modules.join(dependency);
        candidate
            .join("package.json")
            .is_file()
            .then_some(candidate)
    })
}

/// What a manifest declares: `license`, or the older `license: {type}` and
/// `licenses: [{type}]` forms.
fn declared_license(manifest: &Value) -> String {
    let of = |value: &Value| {
        value
            .as_str()
            .or_else(|| value.get("type").and_then(Value::as_str))
            .map(str::to_owned)
    };
    manifest
        .get("license")
        .and_then(of)
        .or_else(|| {
            let licenses: Vec<String> = manifest
                .get("licenses")?
                .as_array()?
                .iter()
                .filter_map(of)
                .collect();
            (!licenses.is_empty()).then(|| licenses.join(" OR "))
        })
        .unwrap_or_else(|| "not declared".to_owned())
}

/// A package's license file, if it ships one.
fn license_text(dir: &Path) -> Result<Option<String>> {
    let mut candidates: Vec<PathBuf> = fs::read_dir(dir)
        .with_context(|| format!("Failed to read {}", dir.display()))?
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| path.is_file())
        .filter(|path| {
            path.file_name()
                .map(|name| name.to_string_lossy().to_ascii_uppercase())
                .is_some_and(|name| {
                    name.starts_with("LICENSE")
                        || name.starts_with("LICENCE")
                        || name.starts_with("COPYING")
                })
        })
        .collect();
    candidates.sort();
    candidates
        .first()
        .map(|path| {
            fs::read(path)
                .map(|bytes| String::from_utf8_lossy(&bytes).into_owned())
                .with_context(|| format!("Failed to read {}", path.display()))
        })
        .transpose()
}

fn render_frontend(packages: &BTreeSet<FrontendPackage>) -> String {
    let mut rendered = String::new();
    for package in packages {
        rendered.push_str(&format!(
            "### {}@{}\n\nLicensed `{}`.\n\n",
            package.name, package.version, package.license
        ));
        match &package.text {
            Some(text) => rendered.push_str(&fenced(text)),
            None => rendered.push_str("The package ships no license file.\n"),
        }
        rendered.push('\n');
    }
    rendered
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A package at `dir`, with its `package.json` and maybe a license file.
    fn package(dir: &Path, manifest: &str, license: Option<&str>) {
        fs::create_dir_all(dir).unwrap();
        fs::write(dir.join("package.json"), manifest).unwrap();
        if let Some(license) = license {
            fs::write(dir.join("LICENSE.md"), license).unwrap();
        }
    }

    fn names(packages: &BTreeSet<FrontendPackage>) -> Vec<&str> {
        packages
            .iter()
            .map(|package| package.name.as_str())
            .collect()
    }

    #[test]
    fn dependencies_are_walked_through_node_modules() {
        let root = tempfile::tempdir().unwrap();
        let frontend = root.path().join("src");
        package(
            &frontend,
            r#"{"dependencies": {"direct": "1"}, "devDependencies": {"bundled": "1"}}"#,
            None,
        );
        package(
            &frontend.join("node_modules/direct"),
            r#"{"name": "direct", "version": "1.0.0", "license": "MIT",
                "dependencies": {"transitive": "1"}, "devDependencies": {"tooling": "1"}}"#,
            Some("Direct's license"),
        );
        package(
            &frontend.join("node_modules/transitive"),
            r#"{"name": "transitive", "version": "2.0.0", "license": "ISC"}"#,
            None,
        );
        package(
            &frontend.join("node_modules/bundled"),
            r#"{"name": "bundled", "version": "3.0.0", "license": "MIT"}"#,
            None,
        );
        package(
            &frontend.join("node_modules/tooling"),
            r#"{"name": "tooling", "version": "4.0.0", "license": "MIT"}"#,
            None,
        );

        let packages = frontend_packages(&frontend).unwrap();

        assert_eq!(
            names(&packages),
            ["bundled", "direct", "transitive"],
            "the frontend's dev dependencies count, a dependency's do not"
        );
    }

    /// pnpm keeps a package's own dependencies as its siblings.
    #[test]
    fn a_sibling_in_the_store_resolves() {
        let root = tempfile::tempdir().unwrap();
        let store = root.path().join("store/a/node_modules");
        package(
            &store.join("a"),
            r#"{"name": "a", "version": "1.0.0", "dependencies": {"@scope/b": "1"}}"#,
            None,
        );
        package(
            &store.join("@scope/b"),
            r#"{"name": "@scope/b", "version": "1.0.0"}"#,
            None,
        );
        assert_eq!(
            resolve(&store.join("a"), "@scope/b").unwrap(),
            store.join("@scope/b")
        );
    }

    /// Only this machine's platform packages are installed, so keeping them would
    /// make the file differ between a Mac and a CI runner.
    #[test]
    fn platform_packages_are_neither_listed_nor_walked() {
        let root = tempfile::tempdir().unwrap();
        let frontend = root.path().join("src");
        package(
            &frontend,
            r#"{"dependencies": {"tool": "1"}, "optionalDependencies": {"tool-darwin": "1"}}"#,
            None,
        );
        package(
            &frontend.join("node_modules/tool"),
            r#"{"name": "tool", "version": "1.0.0", "license": "MIT"}"#,
            None,
        );
        package(
            &frontend.join("node_modules/tool-darwin"),
            r#"{"name": "tool-darwin", "version": "1.0.0", "os": ["darwin"], "cpu": ["arm64"],
                "dependencies": {"only-here": "1"}}"#,
            None,
        );
        package(
            &frontend.join("node_modules/only-here"),
            r#"{"name": "only-here", "version": "1.0.0"}"#,
            None,
        );

        assert_eq!(names(&frontend_packages(&frontend).unwrap()), ["tool"]);
    }

    /// Their code ships, so their dependencies count; their own license is ours.
    #[test]
    fn workspace_packages_are_walked_and_not_listed() {
        let root = tempfile::tempdir().unwrap();
        let frontend = root.path().join("src");
        package(
            &frontend,
            r#"{"dependencies": {"@waypoints/domain": "workspace:*"}}"#,
            None,
        );
        package(
            &frontend.join("node_modules/@waypoints/domain"),
            r#"{"name": "@waypoints/domain", "version": "0.1.0", "dependencies": {"zod": "1"}}"#,
            None,
        );
        package(
            &frontend.join("node_modules/zod"),
            r#"{"name": "zod", "version": "4.0.0", "license": "MIT"}"#,
            None,
        );
        assert_eq!(names(&frontend_packages(&frontend).unwrap()), ["zod"]);
    }

    #[test]
    fn an_unmet_optional_dependency_is_not_an_error() {
        let root = tempfile::tempdir().unwrap();
        let frontend = root.path().join("src");
        package(
            &frontend,
            r#"{"optionalDependencies": {"absent": "1"}}"#,
            None,
        );
        assert!(frontend_packages(&frontend).unwrap().is_empty());
    }

    #[test]
    fn every_form_of_declared_license_reads() {
        let declared = |manifest: &str| declared_license(&serde_json::from_str(manifest).unwrap());
        assert_eq!(declared(r#"{"license": "MIT"}"#), "MIT");
        assert_eq!(declared(r#"{"license": {"type": "ISC"}}"#), "ISC");
        assert_eq!(
            declared(r#"{"licenses": [{"type": "MIT"}, {"type": "Apache-2.0"}]}"#),
            "MIT OR Apache-2.0"
        );
        assert_eq!(declared("{}"), "not declared");
    }

    #[test]
    fn packages_render_sorted_with_their_text() {
        let packages = BTreeSet::from([
            FrontendPackage {
                name: "zed".to_owned(),
                version: "1.0.0".to_owned(),
                license: "MIT".to_owned(),
                text: Some("Zed license\n".to_owned()),
            },
            FrontendPackage {
                name: "abc".to_owned(),
                version: "2.0.0".to_owned(),
                license: "ISC".to_owned(),
                text: None,
            },
        ]);

        let rendered = render_frontend(&packages);

        assert!(rendered.find("### abc@2.0.0").unwrap() < rendered.find("### zed@1.0.0").unwrap());
        assert!(rendered.contains("Licensed `ISC`.\n\nThe package ships no license file."));
        assert!(rendered.contains("~~~~text\nZed license\n~~~~"));
    }

    #[test]
    fn registry_entries_are_rendered_with_their_texts() {
        let root = tempfile::tempdir().unwrap();
        let vendored = root.path().join("tooling/vendored");
        fs::create_dir_all(&vendored).unwrap();
        fs::write(vendored.join("LICENSE"), "The upstream license").unwrap();
        fs::create_dir_all(root.path().join("src")).unwrap();
        fs::write(root.path().join("src/ported.rs"), "").unwrap();
        let registry: Registry = toml::from_str(
            r#"
            [[entry]]
            path = "tooling/vendored"
            kind = "crate"
            project = "someone/vendored"
            holder = "Someone"
            license = "Apache-2.0"
            texts = ["LICENSE"]

            [[entry]]
            path = "src/ported.rs"
            kind = "portion"
            project = "someone/routine"
            holder = "Someone Else"
            license = "MIT"
            "#,
        )
        .unwrap();

        let rendered = render_registry(root.path(), &registry).unwrap();

        assert!(rendered.contains("### someone/vendored"), "{rendered}");
        assert!(rendered.contains("The upstream license"), "{rendered}");
        assert!(rendered.contains("### someone/routine"), "{rendered}");
        assert!(
            rendered.contains("Copyright Someone Else. Licensed `MIT`."),
            "{rendered}"
        );
    }
}
