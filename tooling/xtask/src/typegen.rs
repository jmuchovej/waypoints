//! Generates the TypeScript bindings the app consumes from the Rust data model.
//!
//! One command, three files:
//!
//! - `crates/domain/typescript/types.g.ts` — specta export of `domain`'s
//!   registered types.
//! - `crates/domain/typescript/schema.g.ts` — discriminator constants derived
//!   from that export, for code that needs the literals at runtime.
//! - `crates/cartograph/typescript/types.g.ts` — specta export of
//!   `cartograph`'s registered types, with every type `domain` already exports
//!   rewritten into one `import type` from `@waypoints/domain`, so each type
//!   has one identity across the frontend.
//!
//! specta-typescript inlines every referenced type and has no way to reference
//! one from another module, so the cartograph rewrite is text surgery over the
//! emitted file. Both exports are held in memory, each file is written exactly
//! once, and `treefmt` runs over the three paths last so the tree matches what
//! a commit holds. `just check-generated` regenerates these and diffs them.

use anyhow::{Context as _, Result, anyhow, bail};
use heck::ToPascalCase as _;
use specta::Types;
use specta_typescript::Typescript;
use std::collections::BTreeSet;

/// First line of every generated file.
pub const HEADER: &str = "// This file has been generated by `cargo xtask typegen`. DO NOT EDIT.";

/// The package cartograph's bindings import shared types from.
const DOMAIN_PACKAGE: &str = "@waypoints/domain";

/// The three generated files, held in memory until every export has
/// succeeded so a failure writes nothing.
pub struct Exports {
    /// `crates/domain/typescript/types.g.ts`.
    pub domain: String,
    /// `crates/domain/typescript/schema.g.ts`.
    pub schema: String,
    /// `crates/cartograph/typescript/types.g.ts`.
    pub cartograph: String,
}

/// Exports every registered type. Domain's export is always computed — the
/// cartograph rewrite needs its names — whatever the caller then writes.
pub fn exports() -> Result<Exports> {
    let domain = collapse_phase_aliases(&export(&domain_types())?);
    let cartograph = patch_cartograph(
        &collapse_phase_aliases(&export(&cartograph_types())?),
        &domain,
    );
    let schema = derive_schema(&domain)?;
    Ok(Exports {
        domain,
        schema,
        cartograph,
    })
}

