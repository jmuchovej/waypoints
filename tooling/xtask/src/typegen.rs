/// Renders a collection as one TypeScript module, headed by [`HEADER`].
///
/// `serde_json::Value` fields are annotated `#[specta(type = Option<Unknown>)]`
/// at the source, so they render directly as `unknown` — no post-processing.
/// (This also sidesteps specta-typescript's BigInt-forbidden guard, which
/// rejects the `i64`/`u64` inside `serde_json::Number`.)
fn export(types: &Types) -> Result<String> {
    Typescript::default()
        .header(HEADER)
        .export(types, specta_serde::PhasesFormat)
        .map_err(|error| anyhow!("{error}"))
}

/// specta-serde's `PhasesFormat` emits `X = X_Serialize | X_Deserialize` for
/// every type whose serialize/deserialize shapes diverge. The frontend only
/// ever holds serialize-shaped data (the backend serializes across the
/// IPC/HTTP boundary), so collapse each base alias to its serialize phase —
/// otherwise the union blocks property access on divergent types (`RichText`,
/// `MarkData`, …). The `_Deserialize` types remain exported for code that
/// constructs send-payloads.
fn collapse_phase_aliases(export: &str) -> String {
    export
        .lines()
        .map(|line| {
            if let Some(rest) = line.strip_prefix("export type ")
                && let Some((name, rhs)) = rest.split_once(" = ")
                && rhs == format!("{name}_Serialize | {name}_Deserialize;")
            {
                format!("export type {name} = {name}_Serialize;")
            } else {
                line.to_owned()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

// ── Cartograph: import what domain already exports ───────────────────────────

/// Replaces every declaration in `cartograph` whose name `domain` also
/// declares with one sorted `import type` from [`DOMAIN_PACKAGE`]. Declarations
/// travel with their leading JSDoc; everything else is kept in order.
fn patch_cartograph(cartograph: &str, domain: &str) -> String {
    let domain_names = declared_names(domain);
    let lines: Vec<&str> = cartograph.split('\n').collect();

    let mut from_domain = Vec::new();
    let mut local = Vec::new();
    for (name, block) in declaration_blocks(&lines) {
        if domain_names.contains(name) {
            from_domain.push(name);
        } else {
            local.push(block);
        }
    }
    from_domain.sort_unstable();

    let imports = if from_domain.is_empty() {
        String::new()
    } else {
        format!(
            "import type {{ {} }} from \"{DOMAIN_PACKAGE}\";",
            from_domain.join(", ")
        )
    };

    [HEADER, "", &imports, "", &local.join("\n\n"), ""].join("\n")
}

/// The name of the type a line declares, if it is an `export type` line.
fn declared_name(line: &str) -> Option<&str> {
    let rest = line.strip_prefix("export type ")?;
    let end = rest
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .unwrap_or(rest.len());
    (end > 0).then(|| &rest[..end])
}

fn declared_names(export: &str) -> BTreeSet<&str> {
    export.lines().filter_map(declared_name).collect()
}

/// Every declaration in `lines`, as `(name, block)` in file order. A block runs
/// from the declaration's JSDoc (if one immediately precedes it) to the start
/// of the next declaration's, trailing blank lines trimmed.
fn declaration_blocks<'a>(lines: &[&'a str]) -> Vec<(&'a str, String)> {
    let starts: Vec<(&str, usize)> = lines
        .iter()
        .enumerate()
        .filter_map(|(index, line)| declared_name(line).map(|name| (name, index)))
        .collect();

    starts
        .iter()
        .enumerate()
        .map(|(position, &(name, type_line))| {
            let block_start = jsdoc_start(lines, type_line);
            let mut block_end = starts
                .get(position + 1)
                .map(|&(_, next)| jsdoc_start(lines, next))
                .unwrap_or(lines.len());
            while block_end > block_start && lines[block_end - 1].trim().is_empty() {
                block_end -= 1;
            }
            (name, lines[block_start..block_end].join("\n"))
        })
        .collect()
}

/// Where the block for the declaration at `type_line` begins: the opening
/// `/**` of a JSDoc that ends right above it (blank lines allowed), else the
/// declaration line itself.
fn jsdoc_start(lines: &[&str], type_line: usize) -> usize {
    let mut scan = type_line.checked_sub(1);
    while let Some(index) = scan
        && lines[index].trim().is_empty()
    {
        scan = index.checked_sub(1);
    }
    let Some(mut index) = scan else {
        return type_line;
    };
    if !lines[index].trim_end().ends_with("*/") {
        return type_line;
    }
    loop {
        if lines[index].trim_start().starts_with("/**") {
            return index;
        }
        match index.checked_sub(1) {
            Some(previous) => index = previous,
            None => return type_line,
        }
    }
}

// ── Domain: discriminator constants ──────────────────────────────────────────

/// `schema.g.ts`: the `Content` discriminators and `TextMarkKind` literals as
/// `as const` objects with PascalCase keys, for the editor and app layers.
fn derive_schema(domain: &str) -> Result<String> {
    let content = resolve_phased_name("Content", domain);
    let content_types = tagged_discriminators(&content, "type", domain)?;
    let inline = resolve_phased_name("TextMarkKind", domain);
    let inline_kinds = union_literals(&inline, domain)?;

    Ok([
        HEADER,
        "",
        "/** Content block type discriminators — must match Content[\"type\"] from types.g.ts */",
        &const_object("ContentType", &content_types),
        "",
        "/** Inline mark kind discriminators — must match TextMarkKind from types.g.ts */",
        &const_object("InlineKind", &inline_kinds),
        "",
    ]
    .join("\n"))
}

/// `PhasesFormat` splits directional types into `X_Serialize`/`X_Deserialize`
/// and leaves `X` as a bare alias with no inline fields, so prefer the
/// `_Serialize` phase when it exists. Symmetric types keep their base name.
fn resolve_phased_name(name: &str, export: &str) -> String {
    let serialize = format!("{name}_Serialize");
    if declaration_body(&serialize, export).is_some() {
        serialize
    } else {
        name.to_owned()
    }
}

/// The text of `export type <name> = …`, from the declaration to the next
/// top-level `export` (or the end of the file).
fn declaration_body<'a>(name: &str, export: &'a str) -> Option<&'a str> {
    let needle = format!("export type {name}");
    let start = export.match_indices(&needle).find_map(|(start, _)| {
        let after = export[start + needle.len()..].trim_start();
        after.starts_with('=').then_some(start)
    })?;
    let body = &export[start..];
    let end = body.find("\nexport ").unwrap_or(body.len());
    Some(&body[..end])
}

/// `<tag>: "<literal>"` values inside a declaration, in order.
fn tagged_discriminators(name: &str, tag: &str, export: &str) -> Result<Vec<String>> {
    let body = declaration_body(name, export)
        .with_context(|| format!("Could not find type \"{name}\" in the domain export"))?;
    let needle = format!("{tag}:");

    Ok(body
        .match_indices(&needle)
        .filter_map(|(start, _)| {
            let after = body[start + needle.len()..].trim_start();
            let literal = after.strip_prefix('"')?;
            let end = literal.find('"')?;
            (end > 0).then(|| literal[..end].to_owned())
        })
        .collect())
}

/// Every `"<literal>"` inside a declaration, in order.
fn union_literals(name: &str, export: &str) -> Result<Vec<String>> {
    let body = declaration_body(name, export)
        .with_context(|| format!("Could not find type \"{name}\" in the domain export"))?;

    let mut literals = Vec::new();
    let mut rest = body;
    while let Some(open) = rest.find('"') {
        let after = &rest[open + 1..];
        let Some(close) = after.find('"') else { break };
        let literal = after[..close].trim_start();
        if literal.is_empty() {
            rest = after;
        } else {
            literals.push(literal.to_owned());
            rest = &after[close + 1..];
        }
    }
    Ok(literals)
}

fn const_object(name: &str, values: &[String]) -> String {
    let entries = values
        .iter()
        .map(|value| format!("  {}: \"{value}\",", value.to_pascal_case()))
        .collect::<Vec<_>>()
        .join("\n");
    format!("export const {name} = {{\n{entries}\n}} as const;")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_collections_export_under_the_header() {
        for types in [domain_types(), cartograph_types()] {
            let exported = export(&types).unwrap();
            assert_eq!(exported.lines().next(), Some(HEADER));
            assert!(exported.contains("export type "));
        }
    }

    #[test]
    fn phase_aliases_collapse_to_the_serialize_shape() {
        let input = "export type A = A_Serialize | A_Deserialize;\n\
                     export type B = { a: A };\n\
                     export type C = C_Serialize | Other;";
        let output = collapse_phase_aliases(input);
        assert_eq!(
            output,
            "export type A = A_Serialize;\n\
             export type B = { a: A };\n\
             export type C = C_Serialize | Other;"
        );
    }

    #[test]
    fn shared_declarations_become_one_import() {
        let domain = "\
export type Shared = string;
export type Phased = Phased_Serialize;
export type Phased_Serialize = { a: string };
export type Phased_Deserialize = { a?: string };
export type Bare = number;";
        let cartograph = format!(
            "{HEADER}
/**
 * A type domain owns.
 */
export type Shared = string;

export type Bare = number;

/**
 * Cartograph's own.
 */
export type Local = {{
\tshared: Shared,
}};

export type Phased = Phased_Serialize;
export type Phased_Serialize = {{ a: string }};
export type Phased_Deserialize = {{ a?: string }};
"
        );

        let patched = patch_cartograph(&cartograph, domain);

        assert_eq!(
            patched,
            format!(
                "{HEADER}

import type {{ Bare, Phased, Phased_Deserialize, Phased_Serialize, Shared }} from \"{DOMAIN_PACKAGE}\";

/**
 * Cartograph's own.
 */
export type Local = {{
\tshared: Shared,
}};
"
            )
        );
    }

    #[test]
    fn a_declaration_without_shared_types_imports_nothing() {
        let patched =
            patch_cartograph("export type Local = number;", "export type Other = string;");
        assert_eq!(
            patched,
            format!("{HEADER}\n\n\n\nexport type Local = number;\n")
        );
    }

    #[test]
    fn discriminators_become_pascal_case_constants() {
        let domain = "\
export type Content = Content_Serialize;
export type Content_Serialize =
\t| { type: \"paragraph\"; rich_text: RichText }
\t| { type: \"heading-1\"; rich_text: RichText }
\t| { type: \"list-item\" }
\t| { type: \"enum-item\" };
/**
 * Next type's docs mention a \"quoted\" word.
 */
export type TextMarkKind = \"bold\" | \"inline-code\";
export type Unrelated = { type: \"not-included\" };";

        let schema = derive_schema(domain).unwrap();

        assert_eq!(
            schema,
            format!(
                "{HEADER}

/** Content block type discriminators — must match Content[\"type\"] from types.g.ts */
export const ContentType = {{
  Paragraph: \"paragraph\",
  Heading1: \"heading-1\",
  ListItem: \"list-item\",
  EnumItem: \"enum-item\",
}} as const;

/** Inline mark kind discriminators — must match TextMarkKind from types.g.ts */
export const InlineKind = {{
  Bold: \"bold\",
  InlineCode: \"inline-code\",
}} as const;
"
            )
        );
    }

    #[test]
    fn the_real_domain_export_derives_a_schema() {
        let domain = collapse_phase_aliases(&export(&domain_types()).unwrap());
        let schema = derive_schema(&domain).unwrap();
        assert!(schema.contains("  Paragraph: \"paragraph\","));
        assert!(schema.contains("  Bold: \"bold\","));
    }
}
