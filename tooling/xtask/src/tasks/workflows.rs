/// Where a workflow lives, which is also who is allowed to consume it.
#[derive(PartialEq, Eq, strum::EnumIter)]
pub enum WorkflowFamily {
    Waypoints,
    Plugins,
}

impl WorkflowFamily {
    const PREAMBLE: &str = "# Generated from xtask::workflows::";

    fn disclaimer(&self, module: &str) -> String {
        format!(
            concat!(
                "{preamble}{module}{external_disclaimer}\n",
                "# Rebuild with `cargo xtask workflows`. Do not edit this file.\n\n",
                "# $schema: https://www.schemastore.org/github-workflow.json",
            ),
            preamble = Self::PREAMBLE,
            module = module,
            external_disclaimer = if *self == WorkflowFamily::Waypoints {
                ""
            } else {
                " within the Waypoints repository."
            },
        )
    }

    pub fn path(&self) -> PathBuf {
        match self {
            WorkflowFamily::Waypoints => PathBuf::from(".github/workflows"),
            WorkflowFamily::Plugins => PathBuf::from("plugins/workflows"),
        }
    }

    /// Every file in this family carrying our preamble; anything hand-written
    /// is left alone.
    fn generated_files(&self) -> Result<Vec<PathBuf>> {
        let dir = self.path();
        let entries = match fs::read_dir(&dir) {
            Ok(entries) => entries,
            // A family with no workflows yet has nothing to report.
            Err(error) if error.kind() == ErrorKind::NotFound => return Ok(Vec::new()),
            Err(error) => {
                return Err(error).with_context(|| format!("Failed to read {}", dir.display()));
            }
        };

        let mut generated = Vec::new();
        for entry in entries {
            let entry = entry?;
            if !entry.file_type().is_ok_and(|file_type| file_type.is_file()) {
                continue;
            }

            let path = entry.path();
            if fs::read_to_string(&path).is_ok_and(|c| c.starts_with(Self::PREAMBLE)) {
                generated.push(path);
            }
        }

        generated.sort();
        Ok(generated)
    }

    /// Generated files across every family, so a workflow that is renamed or
    /// dropped in Rust cannot survive on disk.
    fn all_generated_files() -> Result<Vec<PathBuf>> {
        Self::iter()
            .map(|family| family.generated_files())
            .collect::<Result<Vec<_>>>()
            .map(|families| families.concat())
    }
}

pub fn run(args: WorkflowArgs) -> Result<()> {
    if !Path::new("src-tauri/").is_dir() || !Path::new("crates/domain/").is_dir() {
        anyhow::bail!("xtask workflows must be run from the project root");
    }

    /// One `release-<channel>.yaml` per channel, all from [`release::workflow`].
    fn release_file(channel: Channel) -> WorkflowFile {
        WorkflowFile::waypoints("release", move |context| {
            release::workflow(channel, context)
        })
        .stem(format!("release-{flavor}", flavor = channel.flavor()))
    }
    let workflows = [
        WorkflowFile::waypoints("check_generated", check_generated::workflow),
        WorkflowFile::waypoints("devenv_update", devenv_update::workflow),
        WorkflowFile::waypoints("pull_request", pull_request::workflow),
        WorkflowFile::waypoints("release_plan", release_plan::workflow),
        release_file(Channel::Nightly),
        release_file(Channel::Preview),
        release_file(Channel::Stable),
    ];

    let checking = args.check;
    let context = WorkflowContext {
        args,
        devenv_files: crate::utils::devenv::managed_files()?,
        android_ndk: crate::utils::devenv::android_ndk_version()?,
        android_jdk: crate::utils::devenv::android_jdk_major()?,
        formatters: crate::utils::mise::formatters()?,
        mise_version: crate::utils::mise::version()?,
    };

    let rendered = workflows
        .iter()
        .map(|workflow| workflow.render(&context))
        .collect::<Result<Vec<_>>>()?;

    if checking {
        check(&rendered)
    } else {
        write(&rendered)
    }
}

/// Writes every workflow, first clearing generated files so a renamed or
/// dropped workflow leaves nothing behind.
fn write(rendered: &[RenderedWorkflow]) -> Result<()> {
    for path in WorkflowFamily::all_generated_files()? {
        fs::remove_file(&path).with_context(|| format!("Failed to remove {}", path.display()))?;
    }

    for workflow in rendered {
        let folder = workflow.path.parent().expect("workflows live in a folder");
        fs::create_dir_all(folder)
            .with_context(|| format!("Failed to create directory: {}", folder.display()))?;
        fs::write(&workflow.path, &workflow.content)
            .with_context(|| format!("Failed to write {}", workflow.path.display()))?;
    }

    Ok(())
}

/// Reports drift without touching the working tree, so it is safe against a
/// dirty checkout.
fn check(rendered: &[RenderedWorkflow]) -> Result<()> {
    let mut drift = Vec::new();

    for workflow in rendered {
        let path = workflow.path.display();
        match fs::read_to_string(&workflow.path) {
            Ok(on_disk) if on_disk == workflow.content => {}
            Ok(_) => drift.push(format!("  {path} differs from what xtask would generate")),
            Err(error) if error.kind() == ErrorKind::NotFound => {
                drift.push(format!("  {path} is missing"));
            }
            Err(error) => return Err(error).with_context(|| format!("Failed to read {path}")),
        }
    }

    let expected: Vec<_> = rendered.iter().map(|workflow| &workflow.path).collect();
    for path in WorkflowFamily::all_generated_files()? {
        if !expected.contains(&&path) {
            drift.push(format!(
                "  {} is generated but no longer has a source module",
                path.display()
            ));
        }
    }

    if drift.is_empty() {
        println!("Workflows are in sync with tooling/xtask.");
        return Ok(());
    }

    anyhow::bail!(
        "{count} generated workflow(s) are stale:\n{drift}\n\nRun `cargo xtask workflows` and commit the result.",
        count = drift.len(),
        drift = drift.join("\n"),
    )
}

#[derive(Clone, AsRef)]
#[as_ref(str)]
pub struct GitSHA(String);

#[derive(Parser)]
pub struct WorkflowArgs {
    /// Report drift instead of writing. Exits non-zero when a generated
    /// workflow on disk differs from what this crate would emit.
    #[arg(long)]
    pub check: bool,

    /// Pin generated workflows to a specific commit, for workflows shipped to
    /// repositories that consume this one.
    #[arg(value_parser = parse_sha)]
    pub sha: Option<GitSHA>,
}

fn parse_sha(value: &str) -> Result<GitSHA, String> {
    const GIT_SHA_LENGTH: usize = 40;
    (value.len() == GIT_SHA_LENGTH)
        .then_some(value)
        .ok_or_else(|| {
            format!(
                "Git SHA has the wrong length! Found {len} chars, expected {GIT_SHA_LENGTH} chars.",
                len = value.len()
            )
        })
        .and_then(|value| {
            let mut tmp = [0; 4];
            value
                .chars()
                .all(|c| u16::from_str_radix(c.encode_utf8(&mut tmp), 16).is_ok())
                .then_some(value)
                .ok_or_else(|| "Not a valid Git SHA".to_owned())
        })
        .and_then(|sha| {
            std::process::Command::new("git")
                .args([
                    "rev-parse",
                    "--quiet",
                    "--verify",
                    &format!("{sha}^{{commit}}"),
                ])
                .output()
                .map_err(|_| "Failed to spawn `git` to verify SHA".to_owned())
                .and_then(|output| {
                    output
                        .status
                        .success()
                        .then_some(sha)
                        .ok_or_else(|| format!("SHA {sha} isn't a valid Git SHA in this repo!"))
                })
        })
        .map(|sha| GitSHA(sha.to_owned()))
}

/// Everything a workflow needs that isn't hard-coded in its own module.
pub struct WorkflowContext {
    pub args: WorkflowArgs,
    /// Files devenv materializes into the working tree. See
    /// [`crate::utils::devenv::managed_files`].
    pub devenv_files: Vec<String>,
    /// The Android NDK devenv installs, so CI provisions the same one. See
    /// [`crate::utils::devenv::android_ndk_version`].
    pub android_ndk: String,
    /// The JDK major version devenv installs. See
    /// [`crate::utils::devenv::android_jdk_major`].
    pub android_jdk: String,
    /// Every mise tool that exists only to format, for release jobs to skip.
    /// See [`crate::utils::mise::formatters`].
    pub formatters: String,
    /// The mise that writes the lockfile, for CI to install the same one.
    /// See [`crate::utils::mise::version`].
    pub mise_version: String,
}

/// Boxed rather than a `fn` pointer so one builder can emit a family of
/// workflows by capturing what varies between them — see `release_file` in
/// [`run`].
type Source = Box<dyn Fn(&WorkflowContext) -> Workflow>;

pub struct WorkflowFile {
    /// Filename stem, kebab-case to match the rest of `.github/`.
    stem: String,
    /// Rust module under `tasks::workflows` that produces this file. Points the
    /// header at real source, which is not always `stem` — every channel of
    /// `release-*.yaml` comes out of `release`.
    module: &'static str,
    source: Source,
    family: WorkflowFamily,
}

impl WorkflowFile {
    pub fn waypoints(
        module: &'static str,
        source: impl Fn(&WorkflowContext) -> Workflow + 'static,
    ) -> Self {
        Self {
            stem: module.to_kebab_case(),
            module,
            source: Box::new(source),
            family: WorkflowFamily::Waypoints,
        }
    }

    /// Overrides the filename for one of several workflows sharing a module.
    pub fn stem(mut self, stem: impl Into<String>) -> Self {
        self.stem = stem.into();
        self
    }

    /// Unused until the first plugin workflow exists.
    pub fn plugin(
        module: &'static str,
        source: impl Fn(&WorkflowContext) -> Workflow + 'static,
    ) -> Self {
        Self {
            stem: module.to_kebab_case(),
            module,
            source: Box::new(source),
            family: WorkflowFamily::Plugins,
        }
    }

    fn render(&self, context: &WorkflowContext) -> Result<RenderedWorkflow> {
        let workflow = (self.source)(context);

        let path = self.family.path().join(format!("{}.yaml", self.stem));
        let body = workflow
            .to_string()
            .map_err(|e| anyhow!("{}: {e:?}", path.display()))?;

        let content = [self.family.disclaimer(self.module), body].join("\n");
        let mut content: String = content
            .lines()
            .map(|line| format!("{}\n", line.trim_end()))
            .collect();
        content.truncate(content.trim_end().len());
        content.push('\n');
        Ok(RenderedWorkflow { path, content })
    }
}

/// A workflow rendered to its final bytes, not yet committed to disk.
struct RenderedWorkflow {
    path: PathBuf,
    content: String,
}
