import 'package:tempo/flavors.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';
import 'package:tempo/src/models.dart';
import './repositories/uuid_repository.dart';
import 'objectbox.g.dart'; // This will be generated by ObjectBox

/// Provides access to the ObjectBox Store throughout the app.
class ObjectBox {
  /// The Store of this app.
  late final Store _store;

  late final Admin _admin;

  late final Box<TaskEntity> _tasks;
  Box<TaskEntity> get tasks => _tasks;

  late final Box<ProjectEntity> _projects;
  Box<ProjectEntity> get projects => _projects;

  late final Box<ActivityEntity> _activities;
  Box<ActivityEntity> get activities => _activities;

  late final Box<UuidRegistry> _uuidRegistry;
  Box<UuidRegistry> get uuidRegistry => _uuidRegistry;

  ObjectBox._create(this._store) {
    if (F.appFlavor == Flavor.development && Admin.isAvailable()) {
      _admin = Admin(_store);
    }

    _tasks = Box<TaskEntity>(_store);
    _projects = Box<ProjectEntity>(_store);
    _activities = Box<ActivityEntity>(_store);
    _uuidRegistry = Box<UuidRegistry>(_store);

    // Initialize UUID service with the registry box
    UuidService.initialize(_uuidRegistry);
  }

  /// Create an instance of ObjectBox to use throughout the app.
  static Future<ObjectBox> create() async {
    final docsDir = await getApplicationDocumentsDirectory();
    final directory = switch (F.appFlavor) {
      Flavor.development => "dev.tempo",
      Flavor.production => "do.tempo",
      Flavor.staging => "dev.tempo",
    };
    // Future<Store> openStore() {...} is defined in the generated objectbox.g.dart
    final store = await openStore(
      directory: p.join(docsDir.path, directory),
      macosApplicationGroup: "group.do.tempo",
    );
    return ObjectBox._create(store);
  }

  List<TaskEntity> getTasks<D>({Condition<TaskEntity>? query, QueryProperty<TaskEntity, D>? order}) {
    var queryBuilder = _tasks.query(query);
    if (order != null) {
      queryBuilder = queryBuilder.order<D>(order, flags: Order.descending);
    }
    final Q = queryBuilder.build();

    return Q.find();
  }

  TaskEntity getTaskByUUID(String uuid) =>
      _tasks.query(TaskEntity_.uuid.equals(uuid)).build().find().single;

  TaskEntity getTaskByID(int id) => _tasks.get(id)!;

  int putTask(TaskEntity task) {
    final id = _tasks.put(task);
    task.registerUuid();
    return id;
  }

  int addTask(TaskEntity task) {
    final id = _tasks.put(task);
    task.registerUuid();
    return id;
  }

  List<int> batchAddTasks(List<TaskEntity> tasks) {
    final ids = _tasks.putMany(tasks);
    for (final task in tasks) {
      task.registerUuid();
    }
    return ids;
  }

  void deleteTask(TaskEntity task) {
    UuidService.unregisterUuid(task.uuid);
    _tasks.remove(task.id);
  }

  List<ProjectEntity> getProjects() {
    final queryBuilder =
        _projects
            .query()
            // .order(ProjectEntity_.createDate, flags: Order.descending)
            .build();

    return queryBuilder.find();
  }

  ProjectEntity? getProjectByUUID(String uuid) =>
      _projects.query(ProjectEntity_.uuid.equals(uuid)).build().find().single;

  ProjectEntity? getProjectByID(int id) => _projects.get(id)!;

  int putProject(ProjectEntity project) {
    final id = _projects.put(project);
    project.registerUuid();
    return id;
  }

  int addProject(ProjectEntity project) {
    final id = _projects.put(project);
    project.registerUuid();
    return id;
  }

  List<int> batchAddProjects(List<ProjectEntity> projects) {
    final ids = _projects.putMany(projects);
    for (final project in projects) {
      project.registerUuid();
    }
    return ids;
  }

  void deleteProject(ProjectEntity project) {
    UuidService.unregisterUuid(project.uuid);
    _projects.remove(project.id);
  }

  List<ActivityEntity> getActivities() {
    final queryBuilder =
        _activities
            .query()
            // .order(ActivityEntity_.createDate, flags: Order.descending)
            .build();

    return queryBuilder.find();
  }

  ActivityEntity? getActivityByUUID(String uuid) =>
      _activities
          .query(ActivityEntity_.uuid.equals(uuid))
          .build()
          .find()
          .single;

  ActivityEntity? getActivityByID(int id) => _activities.get(id)!;

  int putActivity(ActivityEntity activity) => _activities.put(activity);
  int addActivity(ActivityEntity activity) => _activities.put(activity);
  List<int> batchAddActivities(List<ActivityEntity> activities) =>
      _activities.putMany(activities);
  void deleteActivity(ActivityEntity activity) =>
      _activities.remove(activity.id);
}
